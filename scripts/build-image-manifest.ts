import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import sharp from "sharp";
import { IMAGE_ALT_TEXT, IMAGE_EXCLUDED, IMAGE_SLOTS } from "../content/site";

export interface ImageManifestEntry {
  fileName: string;
  src: string;
  width: number;
  height: number;
  orientation: "portrait" | "landscape" | "square";
  blurDataURL: string;
  alt: string;
  sizeBytes: number;
  sha256: string;
  isDuplicate: boolean;
}

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

async function buildManifest() {
  const publicImagesDir = path.join(process.cwd(), "public", "images");
  const contentDir = path.join(process.cwd(), "content");

  if (!fs.existsSync(publicImagesDir)) {
    fs.mkdirSync(publicImagesDir, { recursive: true });
  }
  if (!fs.existsSync(contentDir)) {
    fs.mkdirSync(contentDir, { recursive: true });
  }

  const files = fs
    .readdirSync(publicImagesDir)
    .filter((file) => {
      if (file.startsWith(".")) return false;
      const ext = path.extname(file).toLowerCase();
      return IMAGE_EXTENSIONS.has(ext);
    })
    .sort((a, b) => a.localeCompare(b));

  const seenHashes = new Set<string>();
  const entries: ImageManifestEntry[] = [];

  for (const fileName of files) {
    const filePath = path.join(publicImagesDir, fileName);
    const buffer = fs.readFileSync(filePath);
    const sha256 = crypto.createHash("sha256").update(buffer).digest("hex");
    const isDuplicate = seenHashes.has(sha256);
    seenHashes.add(sha256);

    const metadata = await sharp(buffer).rotate().metadata();
    const width = metadata.width ?? 1200;
    const height = metadata.height ?? 1200;

    let orientation: "portrait" | "landscape" | "square" = "square";
    if (width > height) orientation = "landscape";
    else if (height > width) orientation = "portrait";

    const blurBuffer = await sharp(buffer)
      .rotate()
      .resize(20, 20, { fit: "inside" })
      .webp({ quality: 40 })
      .toBuffer();

    const blurDataURL = `data:image/webp;base64,${blurBuffer.toString("base64")}`;
    const alt =
      IMAGE_ALT_TEXT[fileName] ??
      "Oludamade & Miracle celebrating their love story";

    entries.push({
      fileName,
      src: `/images/${encodeURIComponent(fileName).replace(/%2F/g, "/")}`,
      width,
      height,
      orientation,
      blurDataURL,
      alt,
      sizeBytes: buffer.byteLength,
      sha256,
      isDuplicate,
    });
  }

  const outputJsonPath = path.join(contentDir, "images.generated.json");
  fs.writeFileSync(
    outputJsonPath,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        totalFiles: entries.length,
        uniqueFiles: entries.filter((e) => !e.isDuplicate).length,
        images: entries,
      },
      null,
      2
    ) + "\n",
    "utf8"
  );

  // Generate human-readable /content/image-manifest.md
  const usageMap = new Map<string, string[]>();
  const addUsage = (file: string | undefined, slot: string) => {
    if (!file) return;
    const list = usageMap.get(file) ?? [];
    list.push(slot);
    usageMap.set(file, list);
  };

  addUsage(IMAGE_SLOTS.heroMobile, "Hero (Mobile portrait)");
  addUsage(IMAGE_SLOTS.heroDesktop, "Hero (Desktop)");
  IMAGE_SLOTS.story.forEach((file, idx) =>
    addUsage(file, `Our Story — Chapter ${idx + 1}`)
  );
  Object.entries(IMAGE_SLOTS.weddingParty).forEach(([name, file]) =>
    addUsage(file, `Wedding Party — ${name}`)
  );

  const mdLines: string[] = [
    "# Image Manifest — Oludamade & Miracle",
    "",
    "This file is auto-generated by `scripts/build-image-manifest.ts` from `/public/images/`.",
    "To swap or add photos, place them in `/public/images/`, update slot names in `content/site.ts`, and run `npm run build:images`.",
    "",
    "| File | Dimensions | Orientation | Used In | Alt Text |",
    "| --- | --- | --- | --- | --- |",
  ];

  for (const entry of entries) {
    const slots = usageMap.get(entry.fileName) ?? [];
    const excluded = IMAGE_EXCLUDED.includes(entry.fileName) || entry.isDuplicate;
    const isPartyOnly = Object.values(IMAGE_SLOTS.weddingParty).includes(
      entry.fileName
    );
    if (!excluded && !isPartyOnly) {
      slots.push("Gallery");
    } else if (entry.isDuplicate) {
      slots.push("Skipped (exact duplicate)");
    } else if (IMAGE_EXCLUDED.includes(entry.fileName)) {
      slots.push("Excluded from gallery");
    }

    mdLines.push(
      `| \`${entry.fileName}\` | ${entry.width}×${entry.height} | ${entry.orientation} | ${slots.join(", ")} | ${entry.alt} |`
    );
  }

  fs.writeFileSync(
    path.join(contentDir, "image-manifest.md"),
    mdLines.join("\n") + "\n",
    "utf8"
  );

  console.log(
    `Built image manifest: ${entries.length} files (${entries.filter((e) => !e.isDuplicate).length} unique).`
  );
}

buildManifest().catch((err) => {
  console.error("Failed to build image manifest:", err);
  process.exit(1);
});
